"""Build all synthetic case artifacts.

For each cases/case_*.json, writes to output/<case_id>/:
  radiology.pdf          what the patient uploads (imaging report)
  labs.pdf               what the patient uploads (lab results)
  history.pdf            what the patient uploads (PCP health summary or questionnaire)
  intake_expected.json   FHIR-shaped JSON the Intake agent should produce
and regenerates CASES.md (index of scenarios). The answer_key stays in the case
file only, so agents never see it.

    uv run --with reportlab python data/build.py
"""

from __future__ import annotations

import json
from pathlib import Path

import history
import labs
import network
import render

ROOT = Path(__file__).parent
CASES = ROOT / "cases"
OUTPUT = ROOT / "output"


def load_cases() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(CASES.glob("case_*.json"))]


def strip_private(obj):
    if isinstance(obj, dict):
        return {k: strip_private(v) for k, v in obj.items() if not k.startswith("_")}
    if isinstance(obj, list):
        return [strip_private(v) for v in obj]
    return obj


def report_text(dr: dict) -> str:
    parts = []
    for s in dr["_sections"]:
        parts.append(f"{s['title']}:")
        if "text" in s:
            parts.append(s["text"])
        parts += [f"{i['label']}: {i['text']}" for i in s.get("items", [])]
        parts.append("")
    parts += ["IMPRESSION:", dr["conclusion"]]
    return "\n".join(parts)


def intake_expected(case: dict) -> dict:
    dr = strip_private(case["DiagnosticReport"])
    dr["presentedForm"] = [{"contentType": "text/plain", "text": report_text(case["DiagnosticReport"])}]
    sex = case["Patient"]["gender"]
    return {
        "case_id": case["case_id"],
        "Patient": strip_private(case["Patient"]),
        "Coverage": strip_private(case["Coverage"]),
        "DiagnosticReport": dr,
        "LabReports": [r for order in case["labs"] for r in labs.to_fhir(order, sex)],
        "History": {"source": case["history"]["source"], "resources": history.to_fhir(case["history"])},
        "intake": case["intake"],
    }


def write_index(cases: list[dict]) -> None:
    lines = [
        "# Synthetic cases",
        "",
        "Generated by `build.py` from `cases/*.json`. SYNTHETIC; hackathon prototype, not medical advice.",
        "",
        "| Case | Patient | Exam | Plan | Answers the indication | Incidental findings (triage) | Lab links |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in cases:
        pt, dr = c["Patient"], c["DiagnosticReport"]
        age = render.age_on(pt["birthDate"], dr["effectiveDateTime"])
        ak = c["answer_key"]
        answered = "; ".join(a["finding"] for a in ak if a["source"] == "radiology" and not a["incidental"])
        inc = "; ".join(
            f"{a['finding']} ({a['triage']}{', not in impression' if a.get('in_impression') is False else ''})"
            for a in ak
            if a["source"] == "radiology" and a["incidental"]
        )
        lab = "; ".join(f"{a['finding']} ({a['triage']})" for a in ak if a["source"] != "radiology")
        lines.append(
            f"| {c['case_id']} | {age}{pt['gender'][0].upper()}, {pt['address'][0]['postalCode']} "
            f"| {dr['code']['text']} | {c['Coverage']['class'][0]['value']} | {answered or '-'} "
            f"| {inc or 'none'} | {lab or '-'} |"
        )
    lines += ["", "Scenarios:", ""]
    lines += [f"- **{c['case_id']}**: {c['_scenario']}" for c in cases]
    (ROOT / "CASES.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    cases = load_cases()
    for case in cases:
        network.get_plan(case["Coverage"]["class"][0]["value"])
        out = OUTPUT / case["case_id"]
        out.mkdir(parents=True, exist_ok=True)
        render.render_radiology(case, out / "radiology.pdf")
        render.render_labs(case, out / "labs.pdf")
        render.render_history(case, out / "history.pdf")
        (out / "intake_expected.json").write_text(json.dumps(intake_expected(case), indent=2) + "\n")
        print(f"built {out.relative_to(ROOT.parent)}")
    write_index(cases)


if __name__ == "__main__":
    main()
